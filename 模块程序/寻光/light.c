/*==========================================================================
 * light.c  ——  寻光（块④）最简程序
 *--------------------------------------------------------------------------
 * 芯片：STC89C52RC，晶振 11.0592 MHz
 *
 * 上电就寻光：
 *      两边都亮    ->  直走
 *      只有左边亮  ->  左转
 *      只有右边亮  ->  右转
 *      两边都暗    ->  停车
 *
 * 引脚：
 *      P1.1 = 左光敏，见光 = 低（0）
 *      P1.0 = 右光敏，见光 = 低（0）
 *      P0.0~P0.3 = IN1~IN4（L293D 方向）
 *      P0.4 = ENA，P0.5 = ENB（高 = 使能）
 *      P0.6 = 蜂鸣器（1 = 静音）
 *      P2    = 数码管（固定显示 "L"）
 *
 * 电机：P0 整个字节直接写，不再定义动作码
 *      直走 0xF5 = 0x80 | 0x05 | 0x10 | 0x20 | 0x40
 *      左转 0xF6 = 0x80 | 0x06 | 0x10 | 0x20 | 0x40
 *      右转 0xF9 = 0x80 | 0x09 | 0x10 | 0x20 | 0x40
 *      停车 0xC0 = 四个方向位全 0，两个使能也拉低
 *==========================================================================*/

#include <reg52.h>

sbit LDR_LEFT  = P1^1;          /* 左光敏：见光 = 低 */
sbit LDR_RIGHT = P1^0;          /* 右光敏：见光 = 低 */

void main(void)
{
    P0 = 0xC0;                  /* 上电先停车 */
    P2 = 0xE3;                  /* 数码管显示 "L" */

    while (1) {
        if (!LDR_LEFT && !LDR_RIGHT) {
            P0 = 0xF5;          /* 两边都亮：直走 */
        } else if (!LDR_LEFT) {
            P0 = 0xF6;          /* 只有左边亮：左转 */
        } else if (!LDR_RIGHT) {
            P0 = 0xF9;          /* 只有右边亮：右转 */
        } else {
            P0 = 0xC0;          /* 两边都暗：停车 */
        }
    }
}
