def sec_problems(d):
    d.h1("三、遇到的问题与解决方法")

    d.h2("1. 程序总是下载不进去")
    d.body("一开始怎么点下载都失败，把电源开关关了再开也没用，把电池拔了还是没用，但只插 USB 的时候就能下载。"
           "后来试了三种接法对比才发现原因：板上的电源开关只控制 USB 那一路线，电池那条线是绕过去的，"
           "（2026-09-20 更正：原据此推断的「USB 与电池同时接就断不了电」已被实测推翻——同时接也能正常下载。）"
           "STC 下载必须趁单片机刚上电那一瞬间握手，所以做法是：点完【下载/编程】，"
           "把开关关掉、等一两秒再打开（不用拔电池）。跑车的时候再装电池、拔掉 USB。")

    d.h2("2. 超声波模块插上不工作、还发热")
    d.body("模块顺着插座一插上去就不工作，还有点发热。查原理图发现，板上这个 4 芯插座按脚号是"
           "「地、Echo、Trig、电源」，而模块自己的脚序是「电源、Trig、Echo、地」，两边正好是反的，"
           "直接插上去等于把电源接到地上。改成用四根杜邦线按板子上的丝印一根一根接，接好就正常了。"
           "所以以后插任何模块之前，都要先看清插座脚序，必要时先不插模块、只上电量一下各脚电压。")

    d.h2("3. 数码管显示整体错位一位")
    d.body("第一次点亮数码管时，显示的笔画整体串了一位。我用程序把每一段单独点亮，"
           "再回到原理图上核对每根线接的是哪个脚，最后确认段序是反着接的："
           "第一位接的其实是最高位引脚；而且 P2.0 那个脚接的是板上的指示灯，不是数码管的段。"
           "按实际顺序重写段码表以后显示就正常了。")

    d.h2("4. 按遥控器没反应，串口一打印就解不出正确键值")
    d.body("这个现象很怪：小车能正常启动，但按遥控器不动；更奇怪的是按不同按键，程序解出来的却是同一个值。"
           "算一下时间就明白了——串口 9600 波特率下打印一行四十来个字符要 42 毫秒，"
           "而一帧红外信号只有 67 毫秒，打印的时候把下一帧的开头错过了，"
           "每次都从中间开始截，自然每次都解出同一个错误值。解决办法是给调试打印加一个开关，"
           "正式用的时候关掉，问题就没有了，顺便还省下三百多字节的程序空间。")

    d.h2("5. 循迹时左右转反了")
    d.body("小车循迹时往远离黑线的方向转，说明左右判断写反了。我先用遥控器的左转、右转确认电机本身没有接反，"
           "然后按几何关系重新推：小车正常是骑在黑线上跑的，如果只有左边的探头压到黑线，"
           "说明车身已经偏到线的右边，这时候应该往左转。按这个规则检查程序，果然是两条判断写反了，改过来就好。"
           "需要说明的是，改完以后还没上车实际跑过复核，所以只能说「已经改正，等待上车复核」。")

    d.h2("6. 一开调速电机就乱抽")
    d.body("加上调速功能以后电机有时乱抖。原因是主程序和定时器中断里都在写同一个 P0 口，两边互相覆盖。"
           "改成主程序只改方向变量和速度变量，P0 口统一由定时器中断去写，问题就解决了。")

    d.h2("7. 编译提示程序超出代码大小限制")
    d.body("编译链接时报「评估版 0800H 字节限制」，因为用的是未注册的 Keil 评估版，上限 2 KB。"
           "先把调试打印关掉，一下子省了三百多字节；正式程序改用汇编写，比 C 语言省很多。"
           "最后程序体积从八百多字节做到一千七百多字节，还剩余量。")
    d.image(photo(7), width_cm=6.0, caption="图 3-1 现场照片（7）")
    d.image(photo(8), width_cm=6.0, caption="图 3-2 现场照片（8）")


